/** HSL channel values without the hsl() wrapper — matches shadcn convention. */
export interface PaletteColorTokens {
  background: string
  foreground: string
  card: string
  cardForeground: string
  popover: string
  popoverForeground: string
  primary: string
  primaryForeground: string
  secondary: string
  secondaryForeground: string
  muted: string
  mutedForeground: string
  accent: string
  accentForeground: string
  border: string
  input: string
  ring: string
  sidebarPrimary: string
}

export interface GlassEffect {
  /** CSS length, e.g. "16px" */
  blur: string
  /** 0–1 opacity for translucent surfaces */
  surfaceOpacity: number
  /** Optional border highlight opacity for glass edges */
  borderOpacity?: number
  /** Optional dark-mode overrides */
  dark?: {
    blur?: string
    surfaceOpacity?: number
    borderOpacity?: number
  }
}

export interface ThemePaletteDefinition {
  id: string
  label: string
  description: string
  preview: { light: string; dark: string }
  previewVariant?: "default" | "glass"
  previewGradient?: string
  light: PaletteColorTokens
  dark: PaletteColorTokens
  /** When present, enables global glassmorphism for this palette */
  glass?: GlassEffect
}

export type ThemePaletteId = (typeof THEME_PALETTES)[number]["id"]

